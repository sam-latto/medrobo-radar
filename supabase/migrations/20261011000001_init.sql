-- ── Per-user data ────────────────────────────────────────────────────────────

create table public.subscriptions (
  user_id uuid not null references public.profiles(id) on delete cascade,
  industry_id text not null references public.industries(id),
  focus text,
  created_at timestamptz not null default now(),
  primary key (user_id, industry_id)
);
create index subscriptions_industry on public.subscriptions (industry_id);

create table public.custom_industry_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  label text not null,
  matched_industry_id text references public.industries(id),
  status text not null default 'pending_review'
    check (status in ('focus', 'pending_review', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create table public.watchlist (
  user_id uuid not null references public.profiles(id) on delete cascade,
  company_id bigint not null references public.companies(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, company_id)
);

create table public.resumes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  filename text,
  storage_path text,
  text text not null,
  role_types text[] not null default '{}',
  created_at timestamptz not null default now()
);
create index resumes_user on public.resumes (user_id);

create table public.job_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  role_types text[] not null default '{}',
  custom_role_types text not null default '',
  locations text[] not null default '{}',
  include_remote boolean not null default true,
  remote_only boolean not null default false,
  seniority text[] not null default '{}',
  industry_ids text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table public.job_matches (
  user_id uuid not null references public.profiles(id) on delete cascade,
  job_id bigint not null references public.job_postings(id) on delete cascade,
  resume_id uuid not null references public.resumes(id) on delete cascade,
  score int not null,
  summary text,
  strengths jsonb,
  gaps jsonb,
  level_fit text,
  industry_match boolean,
  created_at timestamptz not null default now(),
  primary key (user_id, job_id, resume_id)
);
create index job_matches_user_score on public.job_matches (user_id, score desc);

create table public.resume_advice (
  user_id uuid not null references public.profiles(id) on delete cascade,
  resume_id uuid not null references public.resumes(id) on delete cascade,
  kind text not null,
  key text not null,
  content jsonb not null,
  created_at timestamptz not null default now(),
  primary key (user_id, resume_id, kind, key)
);

-- ── Usage metering and background tasks ──────────────────────────────────────

create table public.usage_events (
  id bigint generated always as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  industry_id text references public.industries(id),
  action text not null,
  model text,
  input_tokens int,
  output_tokens int,
  cost_usd numeric(10, 4) not null default 0,
  created_at timestamptz not null default now()
);
create index usage_events_user_action on public.usage_events (user_id, action, created_at);
create index usage_events_created on public.usage_events (created_at);

create table public.tasks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null,
  status text not null default 'queued'
    check (status in ('queued', 'running', 'complete', 'failed')),
  progress jsonb,
  result jsonb,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index tasks_user on public.tasks (user_id, created_at desc);

-- ── Access: no anonymous access at all ───────────────────────────────────────

revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
alter default privileges in schema public revoke all on tables from anon;
alter default privileges in schema public revoke all on sequences from anon;

-- ── Row-level security ───────────────────────────────────────────────────────

do $$
declare t text;
begin
  foreach t in array array[
    'plans', 'communities', 'profiles', 'industries', 'pipeline_runs', 'companies',
    'company_industries', 'events', 'briefs', 'job_boards', 'job_board_checks',
    'job_postings', 'job_posting_industries', 'cache', 'subscriptions',
    'custom_industry_requests', 'watchlist', 'resumes', 'job_preferences',
    'job_matches', 'resume_advice', 'usage_events', 'tasks'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

-- Shared data: any signed-in user can read; only the service connection writes.
do $$
declare t text;
begin
  foreach t in array array[
    'plans', 'communities', 'industries', 'pipeline_runs', 'companies',
    'company_industries', 'events', 'briefs', 'job_boards', 'job_postings',
    'job_posting_industries'
  ] loop
    execute format('create policy "signed-in users can read" on public.%I for select to authenticated using (true)', t);
    execute format('revoke insert, update, delete, truncate on public.%I from authenticated', t);
  end loop;
end $$;

-- Worker-only tables: nothing for users.
revoke all on public.job_board_checks, public.cache from authenticated;

-- Profiles: read your own row; change only your own settings.
create policy "users read own profile" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);
create policy "users update own profile" on public.profiles
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
revoke insert, update, delete, truncate on public.profiles from authenticated;
grant update (display_name, email_brief_opt_in, onboarded_at) on public.profiles to authenticated;

-- Per-user tables: full access to your own rows only.
do $$
declare t text;
begin
  foreach t in array array[
    'subscriptions', 'custom_industry_requests', 'watchlist', 'resumes',
    'job_preferences', 'job_matches', 'resume_advice'
  ] loop
    execute format(
      'create policy "users manage own rows" on public.%I for all to authenticated '
      'using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)', t);
  end loop;
end $$;

-- Usage and tasks: users can see their own; only the API's service connection writes.
create policy "users read own usage" on public.usage_events
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "users read own tasks" on public.tasks
  for select to authenticated using ((select auth.uid()) = user_id);
revoke insert, update, delete, truncate on public.usage_events, public.tasks from authenticated;

-- ── Resume files: private bucket, one folder per user ───────────────────────

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('resumes', 'resumes', false, 5242880,
        array['application/pdf',
              'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
              'text/plain'])
on conflict (id) do nothing;

create policy "users manage own resume files" on storage.objects
  for all to authenticated
  using (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'resumes' and (storage.foldername(name))[1] = (select auth.uid())::text);
