-- Industry Radar: initial schema (see docs/ARCHITECTURE.md section 4-5).
-- Shared industry data is readable by any signed-in user and written only by the
-- worker (service connection). Per-user data is readable/writable only by its owner.

-- ── Plans, communities, users ────────────────────────────────────────────────

create table public.plans (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  limits jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.communities (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  email_domain text not null unique,
  plan_id uuid not null references public.plans(id),
  created_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  community_id uuid not null references public.communities(id),
  email text not null,
  display_name text,
  plan_id uuid references public.plans(id),          -- override; null = community plan
  email_brief_opt_in boolean not null default false,
  onboarded_at timestamptz,
  created_at timestamptz not null default now()
);

-- New sign-ins: only emails whose domain belongs to a community are allowed.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  domain text := lower(split_part(coalesce(new.email, ''), '@', 2));
  community uuid;
begin
  select c.id into community from public.communities c where c.email_domain = domain;
  if community is null then
    raise exception 'Sign-in is limited to approved school accounts (got domain "%")', domain
      using errcode = 'P0001';
  end if;
  insert into public.profiles (id, community_id, email, display_name)
  values (new.id, community, lower(new.email),
          coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ── Industry catalog ─────────────────────────────────────────────────────────

create table public.industries (
  id text primary key,
  parent_id text references public.industries(id),
  name text not null,
  kind text not null check (kind in ('sector', 'industry')),
  profile_yaml text,                                  -- pipeline config
  status text not null default 'needs_review'
    check (status in ('active', 'needs_review', 'retired')),
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

-- ── Shared industry data (written by the worker) ─────────────────────────────

create table public.pipeline_runs (
  id uuid primary key default gen_random_uuid(),
  industry_id text not null references public.industries(id),
  run_date date not null,
  triggered_by text not null,
  status text not null,
  source_counts jsonb,
  cost_usd numeric(10, 4),
  error text,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);
create index pipeline_runs_industry_date on public.pipeline_runs (industry_id, run_date desc);

create table public.companies (
  id bigint generated by default as identity primary key,
  name text not null,
  normalized_name text not null unique,
  description text,
  website text,
  first_seen date,
  last_seen date,
  created_at timestamptz not null default now()
);

create table public.company_industries (
  company_id bigint not null references public.companies(id) on delete cascade,
  industry_id text not null references public.industries(id),
  primary key (company_id, industry_id)
);
create index company_industries_industry on public.company_industries (industry_id);

create table public.events (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.pipeline_runs(id),
  industry_id text not null references public.industries(id),
  company_id bigint references public.companies(id),
  company text,
  product text,
  event_type text not null,
  segment text not null,
  date date,
  summary text not null,
  source_url text not null,
  source_type text not null default 'tavily',
  funding_amount bigint,
  regulatory_status text,
  created_at timestamptz not null default now(),
  unique (industry_id, source_url)
);
create index events_industry_date on public.events (industry_id, date desc);
create index events_company on public.events (company_id);
create index events_run on public.events (run_id);

create table public.briefs (
  id uuid primary key default gen_random_uuid(),
  industry_id text not null references public.industries(id),
  run_id uuid references public.pipeline_runs(id),
  brief_date date not null,
  headline text,
  content_md text not null,
  content jsonb,
  created_at timestamptz not null default now(),
  unique (industry_id, brief_date)
);

-- ── Jobs: shared postings ────────────────────────────────────────────────────

create table public.job_boards (
  provider text not null,
  token text not null,
  company text,
  last_fetched_at timestamptz,
  primary key (provider, token)
);

create table public.job_board_checks (
  normalized_name text primary key,
  checked_at timestamptz not null
);

create table public.job_postings (
  id bigint generated by default as identity primary key,
  url text not null unique,
  provider text not null,
  board_token text,
  company text,
  title text not null,
  location text,
  remote boolean,
  department text,
  employment_type text,
  compensation text,
  description text,
  posted_at text,
  active boolean not null default true,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index job_postings_board on public.job_postings (provider, board_token);

create table public.job_posting_industries (
  job_id bigint not null references public.job_postings(id) on delete cascade,
  industry_id text not null references public.industries(id),
  primary key (job_id, industry_id)
);
create index job_posting_industries_industry on public.job_posting_industries (industry_id);

-- Shared cache (e.g. role-type keyword lists)
create table public.cache (
  key text primary key,
  value jsonb not null,
  expires_at timestamptz,
  updated_at timestamptz not null default now()
